export type CharacterId = 'miro' | 'radio' | 'dog';

export interface Choice {
  label: string;
  nextSceneId: SceneId;
}

export type SceneId =
  | 'scene-1'
  | 'scene-2'
  | 'scene-3'
  | 'scene-4'
  | 'scene-5'
  | 'fork'
  | 'ending-a'
  | 'ending-b';

export interface Scene {
  id: SceneId;
  title: string;
  /** Абзацы текста сцены. */
  text: string[];
  /** Путь к фоновому изображению (относительно BASE_URL) или null, если нет. */
  image: string | null;
  /** Персонажи, появляющиеся в этой сцене. */
  characters: CharacterId[];
  /** Необязательное видео-вставка (autoplay muted loop). */
  video?: string;
  /** Необязательный аудио-сигнал (one-shot эффект). */
  audioCue?: string;
  /** Необязательная подпись кнопки перехода (по умолчанию «Дальше»). */
  continueLabel?: string;
  /** Варианты выбора — превращают сцену в развилку. */
  choices?: Choice[];
  /** Линейный переход к следующей сцене. */
  nextSceneId?: SceneId;
  /** Финальная сцена — показывает EndingScreen. */
  isEnding?: boolean;
  endingType?: 'A' | 'B';
}

